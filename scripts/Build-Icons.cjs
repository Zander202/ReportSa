// Build a small Lucide bundle from the checked-in library; no download needed.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../Municipal.Web');
const lucide = require(path.join(root, 'wwwroot/js/vendor/lucide.min.js'));
const files = directory => fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry =>
    entry.isDirectory() ? files(path.join(directory, entry.name)) : [path.join(directory, entry.name)]);
const names = new Set();
for (const file of [...files(path.join(root, 'Views')),
    path.join(root, 'wwwroot/js/site.js'), path.join(root, 'wwwroot/js/community.js')]) {
    const source = fs.readFileSync(file, 'utf8');
    for (const match of source.matchAll(/data-lucide="([a-z0-9-]+)"|\.lucide\s*=\s*['"]([a-z0-9-]+)['"]|\[Category\.\w+\]\s*=\s*"([a-z0-9-]+)"/g)) {
        names.add(match[1] || match[2] || match[3]);
    }
}
const icons = Object.fromEntries([...names].sort().map(name => {
    const exported = name.replace(/(^|-)([a-z0-9])/g, (_, dash, letter) => letter.toUpperCase());
    if (!lucide.icons[exported]) throw new Error(`Unknown icon: ${name}`);
    return [name, lucide.icons[exported]];
}));
const renderer = `
window.lucide={createIcons(){
const make=([tag,attrs,children=[]])=>{
const el=document.createElementNS('http://www.w3.org/2000/svg',tag);
for(const [key,value] of Object.entries(attrs))el.setAttribute(key,String(value));
for(const child of children)el.appendChild(make(child));return el;};
document.querySelectorAll('i[data-lucide]').forEach(el=>{
const name=el.dataset.lucide,definition=icons[name];if(!definition)return;
const svg=make(definition);
for(const attr of el.attributes)svg.setAttribute(attr.name,attr.value);
svg.classList.add('lucide','lucide-'+name);el.replaceWith(svg);
});}};
`;
const output = path.join(root, 'wwwroot/js/vendor/reportsa-icons.js');
fs.writeFileSync(output, '/** Lucide v0.468.0 - ISC license. Generated by scripts/Build-Icons.cjs. */\n' +
    '(()=>{const icons=' + JSON.stringify(icons) + ';' + renderer + '})();\n');
console.log(`Built ${names.size} icons: ${fs.statSync(output).size} bytes (full library: ${fs.statSync(path.join(root, 'wwwroot/js/vendor/lucide.min.js')).size} bytes).`);
